SELECT E.EMPLOYEE_ID, 
	E.FIRST_NAME,
	E.LAST_NAME,
	D.DEPARTMENT_NAME,
	J.JOB_TITLE,
	E.FIRST_NAME || ' ' || E.LAST_NAME AS MANAGER,
	L.CITY,
	C.COUNTRY_NAME
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
	ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.JOBS J
	ON J.JOB_ID = E.JOB_ID
JOIN HR.EMPLOYEES E 
	ON E.MANAGER_ID = E.EMPLOYEE_ID 
JOIN HR.LOCATIONS L
	ON L.LOCATION_ID = D.LOCATION_ID
JOIN HR.COUNTRIES C
ON C.COUNTRY_ID = L.COUNTRY_ID; 