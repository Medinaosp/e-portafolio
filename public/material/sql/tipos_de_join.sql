-- EJEMPLO LEFT JOIN --
SELECT E.EMPLOYEE_ID,
       E.FIRST_NAME,
       E.LAST_NAME,
       D.DEPARTMENT_NAME
FROM HR.DEPARTMENTS D
     LEFT JOIN HR.EMPLOYEES E
     ON E.DEPARTMENT_ID = D.DEPARTMENT_ID; 
     
-- EJEMPLO FULL OUTER JOIN 
SELECT E.EMPLOYEE_ID,
       E.FIRST_NAME,
       E.LAST_NAME,
       D.DEPARTMENT_NAME
FROM HR.DEPARTMENTS D
     FULL OUTER JOIN HR.EMPLOYEES E
     ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;  

-- EJEMPLO LEFT JOIN EXCLUDIING INNER JOIN 
-- IGUAL CON EL RIHT 
SELECT E.EMPLOYEE_ID,
       E.FIRST_NAME,
       E.LAST_NAME,
       D.DEPARTMENT_NAME
FROM HR.DEPARTMENTS D
     FULL OUTER JOIN HR.EMPLOYEES E
     ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE D.DEPARTMENT_ID IS NULL; 

-- SELF JOIN "ESTAMOS HACIENDO UN JOIN CONTRA LA MISMA TABLA "
SELECT E.FIRST_NAME || ' ' || E.LAST_NAME AS EMPLEADO,
       M.FIRST_NAME || ' ' || M.LAST_NAME AS JEFE
FROM HR.EMPLOYEES E
LEFT JOIN HR.EMPLOYEES M 
ON E.MANAGER_ID = M.EMPLOYEE_ID ; 

-- CROSS JOIN "PRODUCTO CARTESIANO" NO IMPORTA EL ORDEN DE LAS TABLAS 
