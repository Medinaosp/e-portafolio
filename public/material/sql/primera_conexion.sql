-- CREACION DE TABLAS --

CREATE TABLE PAISES AS
SELECT * 
FROM HR.COUNTRIES

CREATE TABLE DEPARTAMENTO AS
SELECT * 
FROM HR.DEPARTMENTS

CREATE TABLE EMPLEADO AS
SELECT * 
FROM HR.EMPLOYEES

CREATE TABLE EMPLEO AS
SELECT * 
FROM HR.JOBS

CREATE TABLE HISTORIAL_TRABAJO AS
SELECT * 
FROM HR.JOB_HISTORY 

CREATE TABLE UBICACION AS
SELECT * 
FROM HR.LOCATIONS

CREATE TABLE REGION AS 
SELECT * 
FROM HR.REGIONS

-- CREACION DE VISTAS --
CREATE OR REPLACE VIEW VW_DEPARTAMENTO
AS
SELECT
    FIRST_NAME,
    LAST_NAME,
    SALARY,
    COUNTRY_NAME
FROM EMPLEADO E
JOIN DEPARTAMENTO D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN UBICACION L
    ON D.LOCATION_ID = L.LOCATION_ID
JOIN PAISES C
    ON L.COUNTRY_ID = C.COUNTRY_ID
JOIN REGION R
    ON C.REGION_ID = R.REGION_ID
WHERE R.REGION_NAME = 'Europe';

-- VERIFICACION DE VISTAS --
SELECT * 
FROM VW_EMPLEADO

SELECT * 
FROM VW_DEPARTAMENTO
